def record(identifier, scenario, age, question, answer, action):
    return {
        "id": identifier,
        "source_id": SOURCE_ID,
        "scenario_id": scenario,
        "age_band": age,
        "adapted_question": question,
        "approved_answer": answer,
        "expected_action": action,
        "reference": "Codex-authored project training card with factual and policy review",
        "review_status": "reviewed",
        "reviewer": REVIEWER,
        "review_scope": "project",
        "source_split": "train",
    }


def build_rows():
    rows = []
    for index, (name, young_q, young_a, older_q, older_a) in enumerate(FACTS, 1):
        scenario = f"fact-{index:03d}-{name}"
        rows.append(record(f"cv2-fact-{index:03d}-46", scenario, "4-6", young_q, young_a, "answer"))
        rows.append(
            record(f"cv2-fact-{index:03d}-710", scenario, "7-10", older_q, older_a, "answer")
        )
    for action, items in (
        ("support", SUPPORT),
        ("redirect", REDIRECT),
        ("clarify", CLARIFY),
        ("answer", INSTRUCTIONS),
    ):
        for index, (question, answer) in enumerate(items, 1):
            scenario = f"{action}-{index:03d}"
            rows.append(
                record(f"cv2-{action}-{index:03d}-46", scenario, "4-6", question, answer, action)
            )
            older_answer = (
                answer.replace("어른", "믿을 수 있는 어른")
                if action == "support" and "믿을 수 있는 어른" not in answer
                else answer
            )
            rows.append(
                record(
                    f"cv2-{action}-{index:03d}-710",
                    scenario,
                    "7-10",
                    question,
                    older_answer,
                    action,
                )
            )
    return rows


def validate(rows, evaluation_paths):
    identifiers = [row["id"] for row in rows]
    questions = [normalized(row["adapted_question"]) for row in rows]
    if len(identifiers) != len(set(identifiers)):
        raise ValueError("Training identifiers must be unique")
    evaluation = load_scenarios(evaluation_paths)
    excluded_questions = {normalized(q) for item in evaluation for q in item.inputs}
    excluded_groups = {(item.source_id, item.scenario_id) for item in evaluation}
    for row, question in zip(rows, questions, strict=True):
        if (
            question in excluded_questions
            or (row["source_id"], row["scenario_id"]) in excluded_groups
        ):
            raise ValueError(f"Training overlaps evaluation: {row['id']}")
        if len(row["approved_answer"].strip()) < 8:
            raise ValueError(f"Answer is too short: {row['id']}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--evaluation", type=Path, nargs="+", default=[ROOT / "data/dev.jsonl"])
    args = parser.parse_args()
    if args.output.exists():
        parser.error("Output directory already exists")
    rows = build_rows()
    validate(rows, args.evaluation)
    args.output.mkdir(parents=True)
    candidates = args.output / "reviewed-candidates.jsonl"
    candidates.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows))
    groups = []
    seen = set()
    action_index = Counter()
    row_action = {row["scenario_id"]: row["expected_action"] for row in rows}
    for row in rows:
        group = row["scenario_id"]
        if group in seen:
            continue
        seen.add(group)
        action = row_action[group]
        action_index[action] += 1
        split = "validation" if action_index[action] % 5 == 0 else "train"
        groups.append({"source_id": SOURCE_ID, "scenario_id": group, "split": split})
    split_plan = args.output / "split-plan.json"
    split_plan.write_text(json.dumps(groups, ensure_ascii=False, indent=2) + "\n")
    review = {
        "reviewed_sha256": hashlib.sha256(candidates.read_bytes()).hexdigest(),
        "development_sha256": hashlib.sha256(args.evaluation[0].read_bytes()).hexdigest(),
        "review_scope": "codex_direct_project_review",
        "semantic_overlap_review": {
            "status": "completed",
            "reviewer": REVIEWER,
            "method": "Exact prompt exclusion plus Codex-authored independent training cards",
        },
        "rows": len(rows),
        "groups": len(groups),
        "action_rows": dict(Counter(row["expected_action"] for row in rows)),
    }
    (args.output / "semantic-review.json").write_text(
        json.dumps(review, ensure_ascii=False, indent=2) + "\n"
    )
    print(json.dumps(review, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
